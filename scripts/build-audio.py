#!/usr/bin/env python3
"""Generate Japanese MP3s offline with Piper. Practice text never leaves this machine."""

import hashlib
import io
import json
import sys
import wave
from pathlib import Path

from piper import PiperVoice
from piper.config import SynthesisConfig

ROOT = Path(__file__).resolve().parents[1]
MODEL = Path("/tmp/piper/voices/ja.onnx")
PUBLIC = ROOT / "public" / "audio" / "ja"
MANIFEST = ROOT / "src" / "content" / "audio-manifest.ts"


def clip_key(slot: int, text: str) -> str:
    return f"{slot % 2}\n{text}"


def main() -> None:
    source = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/spoken.json")
    rows = json.loads(source.read_text())
    PUBLIC.mkdir(parents=True, exist_ok=True)
    voice = PiperVoice.load(str(MODEL))
    clips: dict[str, str] = {}
    failed: list[str] = []
    made = 0
    skipped = 0
    for index, row in enumerate(rows, start=1):
        slot = int(row["slot"]) % 2
        text = str(row["text"]).strip()
        if not text:
            continue
        key = clip_key(slot, text)
        digest = hashlib.sha1(key.encode("utf-8")).hexdigest()[:20]
        rel = f"audio/ja/{digest}.mp3"
        dest = ROOT / "public" / rel
        if dest.exists() and dest.stat().st_size > 400:
            clips[key] = rel
            skipped += 1
            continue
        buf = io.BytesIO()
        try:
            with wave.open(buf, "wb") as wav:
                voice.synthesize_wav(text, wav, syn_config=SynthesisConfig(speaker_id=slot))
        except Exception as exc:  # noqa: BLE001 - keep going and report the line
            failed.append(f"{text[:40]} ({exc})")
            continue
        raw = buf.getvalue()
        if len(raw) < 800:
            failed.append(f"{text[:40]} (empty wav)")
            continue
        dest.write_bytes(encode_mp3(raw))
        if dest.stat().st_size < 200:
            dest.unlink(missing_ok=True)
            failed.append(f"{text[:40]} (empty mp3)")
            continue
        clips[key] = rel
        made += 1
        if index % 40 == 0:
            print(f"{index}/{len(rows)} made={made} skipped={skipped}", flush=True)
    write_manifest(clips)
    print(f"clips {len(clips)} made {made} skipped {skipped} failed {len(failed)}")
    for line in failed[:30]:
        print("FAIL", line)
    if failed:
        sys.exit(1)


def encode_mp3(wav: bytes) -> bytes:
    import subprocess

    proc = subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-i",
            "pipe:0",
            "-ac",
            "1",
            "-ar",
            "22050",
            "-codec:a",
            "libmp3lame",
            "-q:a",
            "6",
            "-f",
            "mp3",
            "pipe:1",
        ],
        input=wav,
        capture_output=True,
        check=True,
    )
    return proc.stdout


def write_manifest(clips: dict[str, str]) -> None:
    body = json.dumps(clips, ensure_ascii=False, indent=2)
    MANIFEST.write_text(
        "/** Generated by scripts/build-audio.py. Keys are `${slot}\\n${sentence}`. */\n"
        "export const audioClips: Record<string, string> = "
        + body
        + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
