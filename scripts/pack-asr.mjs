import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'

const source = process.argv[2] ?? '/tmp/whisper-small'
const outRoot = process.argv[3] ?? '/tmp/asr-branches'
const manifestPath = new URL('../src/lib/asr-pack.ts', import.meta.url)
const partSize = 12 * 1024 * 1024
const branchLimit = 140_000_000
const branches = ['asr-a', 'asr-b']

const files = []
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) await walk(path)
    else files.push(path)
  }
}
await walk(source)
files.sort()

await rm(outRoot, { recursive: true, force: true })
const used = Object.fromEntries(branches.map((name) => [name, 0]))
const packed = []

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex')
}

for (const file of files) {
  const rel = relative(source, file).split('\\').join('/')
  const bytes = await readFile(file)
  const parts = []
  for (let offset = 0, index = 0; offset < bytes.length; offset += partSize, index += 1) {
    const slice = bytes.subarray(offset, Math.min(offset + partSize, bytes.length))
    const name = `${rel}.part${String(index).padStart(2, '0')}`
    const branch = branches.find((item) => used[item] + slice.length <= branchLimit)
    if (!branch) throw new Error(`no branch has room for ${name}`)
    const dest = join(outRoot, branch, name)
    await mkdir(join(outRoot, branch, rel.split('/').slice(0, -1).join('/')), { recursive: true })
    await writeFile(dest, slice)
    used[branch] += slice.length
    parts.push({ branch, path: name })
  }
  packed.push({ path: rel, sha256: sha256(bytes), bytes: bytes.length, parts })
}

for (const branch of branches) {
  const notice = `Whisper small ONNX weights from onnx-community/whisper-small revision 36050c46d777d46dc4b5f43f6d90574fc38f8732.\nThe original Whisper model is MIT licensed. These files are split so a public CDN can serve them.\nAudio recorded in the app is not uploaded here.\n`
  await writeFile(join(outRoot, branch, 'NOTICE.txt'), notice)
}

const body = `/* Generated by scripts/pack-asr.mjs. Weights stay on the asr-a and asr-b branches. */
export const ASR_MODEL_ID = 'onnx-community/whisper-small'
export const ASR_REVISION = '36050c46d777d46dc4b5f43f6d90574fc38f8732'

export const MODEL_MIRROR_BASES = [
  'https://cdn.jsdmirror.com/gh/GodLiy/n1-japanese-practice@',
  'https://cdn.jsdelivr.net/gh/GodLiy/n1-japanese-practice@',
] as const

export const SITE_MIRROR_BASES = [
  'https://cdn.jsdmirror.com/gh/GodLiy/n1-japanese-practice@site/',
  'https://cdn.jsdelivr.net/gh/GodLiy/n1-japanese-practice@site/',
] as const

export const PAGES_URL = 'https://godliy.github.io/n1-japanese-practice/'
export const RELEASES_URL = 'https://github.com/GodLiy/n1-japanese-practice/releases'

export type AsrPart = { branch: 'asr-a' | 'asr-b'; path: string }

export type AsrFile = {
  path: string
  sha256: string
  bytes: number
  parts: AsrPart[]
}

export const ASR_FILES: AsrFile[] = ${JSON.stringify(packed, null, 2)}
`
await writeFile(manifestPath, body)
console.log(JSON.stringify({ used, files: packed.map((file) => ({ path: file.path, bytes: file.bytes, parts: file.parts.length })) }, null, 2))

for (const file of packed) {
  const chunks = []
  for (const part of file.parts) chunks.push(await readFile(join(outRoot, part.branch, part.path)))
  const merged = Buffer.concat(chunks)
  if (merged.length !== file.bytes || sha256(merged) !== file.sha256) throw new Error(`round-trip failed for ${file.path}`)
}
console.log('round-trip ok')
